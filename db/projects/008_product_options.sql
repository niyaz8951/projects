-- Save the mapping of one product (one list for every factory and every user).
--   p_rules:  [{ key, section, sub, component, show, label, strip, response, keywords, kind?, place? }] in display order.
--             A saved row is reviewed; its left-out flag (in_tree) is kept; a rule without kind / place keeps the stored one.
--   p_remove: [key] rows to delete.
-- Rows new to the mapping get the starter keywords while no row of the list carries keywords (once).
create or replace function public.projects_dn_save_rules(p_product_id text, p_rules jsonb, p_remove jsonb, p_show_unmapped boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_user core.profiles; v_prod projects.products; v_removed integer := 0; v_saved integer := 0; v_starter boolean; r record;
begin
  v_user := core.require_tile('projects', 'review');
  v_prod := projects.product(p_product_id);
  p_rules := coalesce(p_rules, '[]'::jsonb); p_remove := coalesce(p_remove, '[]'::jsonb);
  if jsonb_typeof(p_rules) <> 'array' or jsonb_typeof(p_remove) <> 'array' then raise exception 'INVALID:rules'; end if;
  if jsonb_array_length(p_rules) > 3000 then raise exception 'INVALID:rules'; end if;
  if exists (select 1 from jsonb_array_elements(p_rules) e
              where jsonb_typeof(e.value) <> 'object'
                 or char_length(trim(coalesce(e.value ->> 'key', ''))) not between 1 and 300
                 or char_length(coalesce(e.value ->> 'label', '')) > 120 or char_length(coalesce(e.value ->> 'response', '')) > 1000
                 or char_length(coalesce(e.value ->> 'strip', '')) > 300 or char_length(coalesce(e.value ->> 'keywords', '')) > 600
                 or (e.value ? 'kind' and jsonb_typeof(e.value -> 'kind') <> 'null' and coalesce(e.value ->> 'kind', '') not in ('', 'option', 'duty'))
                 or (e.value ? 'place' and jsonb_typeof(e.value -> 'place') <> 'null' and coalesce(e.value ->> 'place', '') not in ('', 'general', 'model'))) then
    raise exception 'INVALID:rules';
  end if;

  with gone as (
    delete from projects.dn_map m
     where m.product_id = v_prod.id
       and m.row_key in (select e.value #>> '{}' from jsonb_array_elements(p_remove) e where jsonb_typeof(e.value) = 'string')
    returning 1)
  select count(*) into v_removed from gone;

  v_starter := not exists (select 1 from jsonb_array_elements(p_rules) e where trim(coalesce(e.value ->> 'keywords', '')) <> '')
           and not exists (select 1 from projects.dn_map m where m.product_id = v_prod.id and m.keywords <> '');

  for r in
    select distinct on (x.key) x.* from (
      select trim(e.value ->> 'key') as key, e.ordinality::integer as ord,
             left(trim(coalesce(e.value ->> 'section', '')), 200) as section, left(trim(coalesce(e.value ->> 'sub', '')), 200) as sub,
             left(trim(coalesce(e.value ->> 'component', '')), 200) as component,
             case when e.value ? 'show' and jsonb_typeof(e.value -> 'show') <> 'null' then (e.value ->> 'show')::boolean else true end as show,
             trim(coalesce(e.value ->> 'label', '')) as label, trim(coalesce(e.value ->> 'strip', '')) as strip,
             trim(coalesce(e.value ->> 'response', '')) as response, trim(coalesce(e.value ->> 'keywords', '')) as keywords,
             case when jsonb_typeof(e.value -> 'kind') = 'string' then e.value ->> 'kind' end as kind,
             case when jsonb_typeof(e.value -> 'place') = 'string' then e.value ->> 'place' end as place
      from jsonb_array_elements(p_rules) with ordinality e) x
    order by x.key, x.ord
  loop
    insert into projects.dn_map as m (product_id, row_key, section, sub, component, show, label, strip, response, keywords, sort_order, updated_by, updated_at, reviewed)
    values (v_prod.id, r.key, r.section, r.sub, r.component, r.show, r.label, r.strip, r.response,
            case when r.keywords <> '' or not v_starter then r.keywords
                 else coalesce((select s.keywords from projects.dn_starter_keywords s where s.product_id = v_prod.id and s.row_key = r.key), '') end,
            r.ord, v_user.id, now(), true)
    on conflict (product_id, row_key) do update set
      section = excluded.section, sub = excluded.sub, component = excluded.component, sort_order = excluded.sort_order,
      updated_by = case when m.show <> excluded.show or m.label <> excluded.label or m.strip <> excluded.strip
                             or m.response <> excluded.response or m.keywords <> r.keywords then excluded.updated_by else m.updated_by end,
      updated_at = case when m.show <> excluded.show or m.label <> excluded.label or m.strip <> excluded.strip
                             or m.response <> excluded.response or m.keywords <> r.keywords then excluded.updated_at else m.updated_at end,
      show = excluded.show, label = excluded.label, strip = excluded.strip, response = excluded.response,
      keywords = r.keywords, reviewed = true;
    if r.kind is not null then update projects.dn_map m set kind = r.kind where m.product_id = v_prod.id and m.row_key = r.key; end if;
    if r.place is not null then update projects.dn_map m set place = r.place where m.product_id = v_prod.id and m.row_key = r.key; end if;
    v_saved := v_saved + 1;
  end loop;

  insert into projects.dn_map_settings (product_id, show_unmapped, updated_by, updated_at)
  values (v_prod.id, coalesce(p_show_unmapped, true), v_user.id, now())
  on conflict (product_id) do update set show_unmapped = excluded.show_unmapped, updated_by = excluded.updated_by, updated_at = excluded.updated_at;
  perform core.audit('projects', 'dn_save_rules', jsonb_build_object('product', v_prod.id, 'saved', v_saved, 'removed', v_removed));
  return jsonb_build_object('saved', v_saved, 'removed', v_removed);
end $$;
revoke execute on function public.projects_dn_save_rules(text, jsonb, jsonb, boolean) from public, anon;
grant execute on function public.projects_dn_save_rules(text, jsonb, jsonb, boolean) to authenticated;

