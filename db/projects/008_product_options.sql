-- Whole rows left out of the tree or brought back, for every factory of the product (dn_map.in_tree).
create or replace function public.projects_po_set_rows_hidden(p_factory_id text, p_row_keys jsonb, p_hidden boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_f projects.factories; v_keys text[]; v_n integer;
begin
  perform core.require_tile('projects', 'review');
  v_f := projects.factory(p_factory_id);
  v_keys := projects.key_list(p_row_keys);
