  perform core.audit('projects', case when coalesce(p_hidden, false) then 'po_rows_left_out' else 'po_rows_back' end,
                     jsonb_build_object('factory', v_f.id, 'rows', to_jsonb(v_keys)));
  return jsonb_build_object('changed', v_n);
end $$;
