-- Add (p_id null) or change one. p_section: the section's name; p_row_key: '' = the whole section, or one row.
create or replace function public.projects_po_save_extra(p_factory_id text, p_id uuid, p_section text, p_row_key text, p_kind text, p_body text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_user core.profiles; v_f projects.factories; v_section text; v_body text; v_id uuid;
begin
  v_user := core.require_tile('projects', 'review');
  v_f := projects.factory(p_factory_id);
  v_section := left(trim(regexp_replace(coalesce(p_section, ''), '\s+', ' ', 'g')), 200);
  v_body := trim(coalesce(p_body, ''));
  if coalesce(p_kind, '') not in ('option', 'note', 'make') then raise exception 'INVALID:kind'; end if;
  if p_kind = 'make' and char_length(v_body) > 120 then raise exception 'INVALID:make'; end if;
  if char_length(v_section) < 1 or char_length(v_section) > 120 then raise exception 'INVALID:section'; end if;
  if v_body = '' or char_length(v_body) > 1000 then raise exception 'INVALID:body'; end if;
  if p_id is null then
    insert into projects.po_extras (factory_id, section, row_key, kind, body, created_by, created_by_name, updated_by, updated_by_name)
    values (v_f.id, v_section, left(trim(coalesce(p_row_key, '')), 300), p_kind, v_body, v_user.id, v_user.username, v_user.id, v_user.username)
    returning id into v_id;
  else
    update projects.po_extras x set kind = p_kind, body = v_body, updated_by = v_user.id, updated_by_name = v_user.username, updated_at = now()
     where x.id = p_id and x.factory_id = v_f.id
    returning x.id into v_id;
    if v_id is null then raise exception 'NOT_FOUND'; end if;
  end if;
  perform core.audit('projects', 'po_save_extra', jsonb_build_object('factory', v_f.id, 'id', v_id, 'kind', p_kind));
  return jsonb_build_object('id', v_id);
end $$;
revoke execute on function public.projects_po_save_extra(text, uuid, text, text, text, text) from public, anon;
grant execute on function public.projects_po_save_extra(text, uuid, text, text, text, text) to authenticated;

create or replace function public.projects_po_delete_extra(p_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_x projects.po_extras;
begin
  perform core.require_tile('projects', 'review');
  delete from projects.po_extras x where x.id = p_id returning * into v_x;
  if v_x.id is not null then
    perform core.audit('projects', 'po_delete_extra', jsonb_build_object('factory', v_x.factory_id, 'id', v_x.id, 'kind', v_x.kind));
  end if;
  return jsonb_build_object('ok', true);
end $$;
revoke execute on function public.projects_po_delete_extra(uuid) from public, anon;
grant execute on function public.projects_po_delete_extra(uuid) to authenticated;

