-- Where option rows show: 'general', 'model' or '' (the card's rule), for every factory of the product. FCU: with
-- p_series the move is for that series only ('' = back to the row's own place).
create or replace function public.projects_po_set_place(p_factory_id text, p_row_keys jsonb, p_place text, p_series text default '')
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_f projects.factories; v_keys text[]; v_mine text[]; v_series text; v_n integer;
begin
  perform core.require_tile('projects', 'review');
  v_f := projects.factory(p_factory_id);
  if coalesce(p_place, '') not in ('', 'general', 'model') then raise exception 'INVALID:place'; end if;
  v_keys := projects.key_list(p_row_keys);
  v_series := left(trim(coalesce(p_series, '')), 60);
  if v_series <> '' then
    select coalesce(array_agg(m.row_key), '{}') into v_mine from projects.dn_map m where m.product_id = v_f.product_id and m.row_key = any (v_keys);
    if cardinality(v_mine) = 0 then raise exception 'NOT_FOUND'; end if;
    if coalesce(p_place, '') = '' then
      delete from projects.po_series_place s where s.product_id = v_f.product_id and s.series = v_series and s.row_key = any (v_mine);
    else
      insert into projects.po_series_place (product_id, series, row_key, place)
      select v_f.product_id, v_series, k, p_place from unnest(v_mine) k
      on conflict (product_id, series, row_key) do update set place = excluded.place;
    end if;
    perform core.audit('projects', 'po_set_place', jsonb_build_object('factory', v_f.id, 'rows', to_jsonb(v_mine), 'place', p_place, 'series', v_series));
    return jsonb_build_object('changed', cardinality(v_mine));
  end if;
  update projects.dn_map m set place = coalesce(p_place, '') where m.product_id = v_f.product_id and m.row_key = any (v_keys);
  get diagnostics v_n = row_count;
  if v_n = 0 then raise exception 'NOT_FOUND'; end if;
  perform core.audit('projects', 'po_set_place', jsonb_build_object('factory', v_f.id, 'rows', to_jsonb(v_keys), 'place', p_place));
  return jsonb_build_object('changed', v_n);
end $$;
revoke execute on function public.projects_po_set_place(text, jsonb, text, text) from public, anon;
grant execute on function public.projects_po_set_place(text, jsonb, text, text) to authenticated;

