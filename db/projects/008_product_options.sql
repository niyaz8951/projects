-- Projects tile, step 5 (Product Options): what each factory has offered so far, per product and factory, and the
-- product's row mapping. Rewritten from the old tool's po_get_tree, po_admin_save_extra, po_admin_delete_extra,
-- po_admin_set_hidden, po_admin_set_place, po_admin_set_kind, po_admin_approve, po_admin_clear_ungrouped, po_reset
-- (worker/src/api/po.ts) and dn_admin_save_rules (dn.ts), with the same checks. Left out: AI notes (no AI).
-- Who: the tree is read by anyone with the tile (the Product Options panel of a datasheet row); a user without
-- 'review' gets the approved values only and no row left out of the tree. Everything that changes Product Options or
-- the row mapping needs 'review' (tile admins and the super user hold it). The reset is for the super user.
-- What a row is (option / duty figure / accessory, the old lib/po-kind.ts) is worked out in the browser (pr-picks.js),
-- the one copy of that rule; the database keeps the editor's choice (dn_map.kind) and the values.
-- Touches only: schema projects and functions public.projects_*. Run after 007_review.sql.

-- ---------------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------------

-- the order values were first read in (the old rowid): Filter 1 before Filter 2, as on the datasheet
alter table projects.po_values add column if not exists seq bigint generated by default as identity;

-- special options, notes and makes typed by the reviewers, per factory: for a section (row_key '') or one row;
-- a make for one fan family has row_key 'family:<name>'
create table projects.po_extras (
  id              uuid primary key default gen_random_uuid(),
  factory_id      text not null references projects.factories (id) on delete cascade,
  section         text not null check (char_length(section) between 1 and 120),
  row_key         text not null default '' check (char_length(row_key) <= 300),
  kind            text not null check (kind in ('option', 'note', 'make')),
  body            text not null check (char_length(body) between 1 and 1000),
  created_by      uuid,
  created_by_name text not null default '',
  created_at      timestamptz not null default now(),
  updated_by      uuid,
  updated_by_name text not null default '',
  updated_at      timestamptz not null default now()
);
create index po_extras_factory on projects.po_extras (factory_id);
alter table projects.po_extras enable row level security;

-- FCU: rows a reviewer moved in one series only (general / per model)
create table projects.po_series_place (
  product_id text not null references projects.products (id) on delete cascade,
  series     text not null check (char_length(series) between 1 and 60),
  row_key    text not null,
  place      text not null check (place in ('general', 'model')),
  primary key (product_id, series, row_key)
);
alter table projects.po_series_place enable row level security;

