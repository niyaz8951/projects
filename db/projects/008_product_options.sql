-- Approve values read from datasheets (they become the factory's: users, the chips, the selection list and the Excel
-- see them) or reject them (deleted; seen again on a later datasheet, a value waits again).
-- p_items: [{ key, model, grp, value_key }] (up to 500); or p_all = true: every value of the factory that waits.
create or replace function public.projects_po_approve(p_factory_id text, p_items jsonb, p_all boolean, p_approve boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_user core.profiles; v_f projects.factories; v_n integer := 0;
begin
  v_user := core.require_tile('projects', 'review');
  v_f := projects.factory(p_factory_id);
  if coalesce(p_all, false) then
    if coalesce(p_approve, false) then
      update projects.po_values v set approved = true, approved_by = v_user.id, approved_at = now() where v.factory_id = v_f.id and not v.approved;
    else
      delete from projects.po_values v where v.factory_id = v_f.id and not v.approved;
    end if;
    get diagnostics v_n = row_count;
  else
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 500 then
      raise exception 'INVALID:items';
    end if;
    with it as (
      select coalesce(i.value ->> 'key', '') as row_key, coalesce(i.value ->> 'model', '') as model,
             coalesce(i.value ->> 'grp', '') as grp, coalesce(i.value ->> 'value_key', '') as value_key
      from jsonb_array_elements(p_items) i where jsonb_typeof(i.value) = 'object'
    ), done as (
      update projects.po_values v set approved = true, approved_by = v_user.id, approved_at = now()
        from it where coalesce(p_approve, false) and v.factory_id = v_f.id and not v.approved
         and v.row_key = it.row_key and v.model = it.model and v.grp = it.grp and v.value_key = it.value_key
      returning 1
    ), gone as (
      delete from projects.po_values v using it
       where not coalesce(p_approve, false) and v.factory_id = v_f.id and not v.approved
         and v.row_key = it.row_key and v.model = it.model and v.grp = it.grp and v.value_key = it.value_key
      returning 1
    )
    select (select count(*) from done) + (select count(*) from gone) into v_n;
  end if;
  if v_n = 0 then raise exception 'INVALID:nothing'; end if;
  perform core.audit('projects', case when coalesce(p_approve, false) then 'po_approve' else 'po_reject' end,
                     jsonb_build_object('factory', v_f.id, 'values', v_n, 'all', coalesce(p_all, false)));
  return jsonb_build_object('changed', v_n);
end $$;
revoke execute on function public.projects_po_approve(text, jsonb, boolean, boolean) from public, anon;
grant execute on function public.projects_po_approve(text, jsonb, boolean, boolean) to authenticated;

-- Old readings: values of a section read before the columns existed. p_drop: [{ key, grp }] exactly the values to
-- remove, named by the page (up to 500); without it, the values without a group in rows of the section that also have
-- grouped values, plus the groups named in p_groups (an older layout, up to 90). Only rows of this product's mapping.
create or replace function public.projects_po_clear_ungrouped(p_factory_id text, p_section text, p_drop jsonb default null, p_groups jsonb default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_f projects.factories; v_section text; v_n integer := 0; v_g integer := 0; v_groups text[];
begin
  perform core.require_tile('projects', 'review');
  v_f := projects.factory(p_factory_id);
  v_section := trim(regexp_replace(coalesce(p_section, ''), '\s+', ' ', 'g'));
  if v_section = '' then raise exception 'INVALID:section'; end if;
  if p_drop is not null then
    if jsonb_typeof(p_drop) <> 'array' or jsonb_array_length(p_drop) = 0 or jsonb_array_length(p_drop) > 500 then raise exception 'INVALID:items'; end if;
    with d as (
      select coalesce(e.value ->> 'key', '') as row_key, coalesce(e.value ->> 'grp', '') as grp
      from jsonb_array_elements(p_drop) e where jsonb_typeof(e.value) = 'object'
    ), gone as (
      delete from projects.po_values v using d
       where v.factory_id = v_f.id and d.row_key <> '' and v.row_key = d.row_key and v.grp = d.grp
         and exists (select 1 from projects.dn_map m where m.product_id = v_f.product_id and m.row_key = v.row_key)
      returning 1)
    select count(*) into v_n from gone;
  else
    delete from projects.po_values v
     where v.factory_id = v_f.id and v.grp = ''
       and v.row_key in (select m.row_key from projects.dn_map m where m.product_id = v_f.product_id and lower(m.section) = lower(v_section))
       and v.row_key in (select g.row_key from projects.po_values g where g.factory_id = v_f.id and g.grp <> '');
    get diagnostics v_n = row_count;
    if p_groups is not null and jsonb_typeof(p_groups) = 'array' then
      select coalesce(array_agg(distinct x), '{}') into v_groups
        from (select e.value #>> '{}' as x from jsonb_array_elements(p_groups) e where jsonb_typeof(e.value) = 'string' limit 90) y where x <> '';
      if cardinality(v_groups) > 0 then
        delete from projects.po_values v
         where v.factory_id = v_f.id and v.grp = any (v_groups)
           and v.row_key in (select m.row_key from projects.dn_map m where m.product_id = v_f.product_id and lower(m.section) = lower(v_section));
        get diagnostics v_g = row_count;
        v_n := v_n + v_g;
      end if;
    end if;
  end if;
  if v_n = 0 then raise exception 'INVALID:nothing'; end if;
  perform core.audit('projects', 'po_clear_ungrouped', jsonb_build_object('factory', v_f.id, 'section', v_section, 'values', v_n));
  return jsonb_build_object('removed', v_n);
end $$;
revoke execute on function public.projects_po_clear_ungrouped(text, text, jsonb, jsonb) from public, anon;
grant execute on function public.projects_po_clear_ungrouped(text, text, jsonb, jsonb) to authenticated;

-- Super user: every value read from datasheets for the product (or one factory of it) is deleted; the next datasheet
-- read brings them back, waiting for approval. p_with_extras also deletes the special options, notes and makes. The row
-- mapping, the compliance library and the projects' datasheet tables are never touched.
create or replace function public.projects_po_reset(p_product_id text, p_factory_id text default null, p_with_extras boolean default false)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_user core.profiles; v_prod projects.products; v_ids text[]; v_values integer; v_extras integer := 0;
begin
  v_user := core.require_tile('projects', 'review');
  if not v_user.is_super then raise exception 'NO_RIGHT'; end if;
  v_prod := projects.product(p_product_id);
  select coalesce(array_agg(f.id), '{}') into v_ids from projects.factories f
   where f.product_id = v_prod.id and (nullif(p_factory_id, '') is null or f.id = p_factory_id);
  if nullif(p_factory_id, '') is not null and cardinality(v_ids) = 0 then raise exception 'INVALID:factory_id'; end if;
  delete from projects.po_values v where v.factory_id = any (v_ids);
  get diagnostics v_values = row_count;
  if coalesce(p_with_extras, false) then
    delete from projects.po_extras x where x.factory_id = any (v_ids);
    get diagnostics v_extras = row_count;
  end if;
  perform core.audit('projects', 'po_reset', jsonb_build_object('product', v_prod.id, 'factory', nullif(p_factory_id, ''),
                     'with_extras', coalesce(p_with_extras, false), 'values_removed', v_values, 'extras_removed', v_extras));
  return jsonb_build_object('values_removed', v_values, 'extras_removed', v_extras);
end $$;
revoke execute on function public.projects_po_reset(text, text, boolean) from public, anon;
grant execute on function public.projects_po_reset(text, text, boolean) to authenticated;

