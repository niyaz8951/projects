-- A list of row keys from the page: an array of strings, trimmed, distinct, none empty, 1 to 500 of them.
create or replace function projects.key_list(p jsonb)
returns text[] language plpgsql immutable as $$
declare out text[];
begin
  if p is null or jsonb_typeof(p) <> 'array' then raise exception 'INVALID:row_keys'; end if;
  select coalesce(array_agg(distinct k), '{}') into out
    from (select trim(e.value #>> '{}') as k from jsonb_array_elements(p) e where jsonb_typeof(e.value) = 'string') x
   where k <> '';
  if cardinality(out) = 0 or cardinality(out) > 500 then raise exception 'INVALID:row_keys'; end if;
  return out;
end $$;

-- ---------------------------------------------------------------------------
-- 3. The tree of one factory
-- ---------------------------------------------------------------------------

-- Anyone with the tile. The rows the mapping shows (not the rows that describe one project), each with its values.
-- A reviewer gets every value (approved or waiting, hidden or not), the rows left out of the tree, the sections he
-- may add to; anyone else the approved values that are not taken out, of the rows in the tree. Extras for everyone.
create or replace function public.projects_po_tree(p_factory_id text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_user core.profiles; v_f projects.factories; v_prod projects.products; v_rev boolean;
begin
  v_user := core.require_tile('projects', null);
  v_f := projects.factory(p_factory_id);
  select * into v_prod from projects.products p where p.id = v_f.product_id;
  v_rev := core.has_tile(v_user.id, 'projects', 'review');
  return jsonb_build_object(
    'factory', jsonb_build_object('id', v_f.id, 'name', v_f.name, 'product_id', v_prod.id, 'product', v_prod.name),
    'can_edit', v_rev, 'can_approve', v_rev,
    'rows', (select coalesce(jsonb_agg(jsonb_build_object(
               'key', m.row_key, 'section', m.section, 'sub', m.sub,
               'component', case when m.label <> '' then m.label else m.component end,
               'hidden', not m.in_tree, 'kind_set', m.kind, 'place', m.place,
               'values', (select coalesce(jsonb_agg(jsonb_build_object('k', v.value_key, 'v', v.value, 'n', v.times, 'hidden', v.hidden,
                                   'model', v.model, 'g', v.grp, 'approved', v.approved, 'seq', v.seq, 'at', v.last_at) order by v.seq), '[]'::jsonb)
                            from projects.po_values v
                           where v.factory_id = v_f.id and v.row_key = m.row_key and (v_rev or (v.approved and not v.hidden))))
             order by m.sort_order, m.row_key), '[]'::jsonb)
             from projects.dn_map m
            where m.product_id = v_prod.id and m.show and not projects.po_skip(m.row_key) and (v_rev or m.in_tree)),
    'extras', (select coalesce(jsonb_agg(jsonb_build_object('id', x.id, 'section', x.section, 'key', x.row_key, 'kind', x.kind, 'body', x.body,
                 'at', x.updated_at, 'by', coalesce(nullif(x.updated_by_name, ''), x.created_by_name)) order by x.created_at, x.id), '[]'::jsonb)
               from projects.po_extras x where x.factory_id = v_f.id),
    'series_place', (select coalesce(jsonb_agg(jsonb_build_object('series', s.series, 'key', s.row_key, 'place', s.place) order by s.series, s.row_key), '[]'::jsonb)
                     from projects.po_series_place s where s.product_id = v_prod.id),
    -- sections a reviewer may add to: shown rows, named, not General, in mapping order
    'sections', case when v_rev then (select coalesce(jsonb_agg(x.section order by x.first), '[]'::jsonb)
                  from (select m.section, min(m.sort_order) as first from projects.dn_map m
                         where m.product_id = v_prod.id and m.show and m.section <> '' and lower(m.section) <> 'general'
                         group by m.section) x) else '[]'::jsonb end);
end $$;
revoke execute on function public.projects_po_tree(text) from public, anon;
grant execute on function public.projects_po_tree(text) to authenticated;

